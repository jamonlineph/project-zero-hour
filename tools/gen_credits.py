#!/usr/bin/env python3
"""Writes game/data/credits.json for the in-game Credits screen (P4-06).

The asset attributions come from ASSET_MANIFEST.csv (one line per author,
source kind and license), so the credits always match the shipped files;
tools/check_repo.py fails if credits.json is out of date. Run it after
adding assets:  python3 tools/gen_credits.py
"""
import csv
import json
import os
import sys

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
OUT = os.path.join(ROOT, "game", "data", "credits.json")

LICENSE_NAMES = {
    "CC-BY-SA-4.0": "Creative Commons Attribution-ShareAlike 4.0",
    "CC-BY-4.0": "Creative Commons Attribution 4.0",
    "CC0-1.0": "CC0 1.0 (public domain)",
    "OFL-1.1": "SIL Open Font License 1.1",
}


def _kind(path):
    parts = path.split("/")
    return parts[2] if len(parts) > 3 else "files"   # game/assets/<kind>/...


def build():
    groups = {}
    with open(os.path.join(ROOT, "ASSET_MANIFEST.csv"), newline="", encoding="utf-8") as f:
        for row in csv.DictReader(f):
            third = row["generated_by"] == "third-party"
            source = row["source"] if third else "made for this game"
            key = (row["author"], row["license"], source)
            g = groups.setdefault(key, {"kinds": set(), "count": 0})
            g["kinds"].add(_kind(row["path"]))
            g["count"] += 1
    assets = []
    for (author, lic, source), g in sorted(groups.items(), key=lambda kv: (kv[0][1] != "CC-BY-SA-4.0", kv[0])):
        assets.append({
            "author": author,
            "what": ", ".join(sorted(g["kinds"])),
            "source": source,
            "license": LICENSE_NAMES.get(lic, lic),
        })
    return {
        "_doc": "Generated by tools/gen_credits.py from ASSET_MANIFEST.csv; don't edit by hand.",
        "game": "Project Zero Hour",
        "made_by": "Project Zero Hour contributors",
        "code_license": "GNU General Public License v3.0 (see LICENSE)",
        "asset_license": "Creative Commons Attribution-ShareAlike 4.0, unless listed otherwise below (see ASSETS_LICENSE.md)",
        "tools": ["Godot Engine (MIT license; its own and third-party notices are under Engine licenses)", "Blender (used to make the placeholder models)"],
        "assets": assets,
        "note": "An original game. Not affiliated with any other game, publisher or government.",
    }


def text():
    return json.dumps(build(), indent=2, ensure_ascii=False) + "\n"


if __name__ == "__main__":
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(text())
    print("wrote", os.path.relpath(OUT, ROOT))
    sys.exit(0)
