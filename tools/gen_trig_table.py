#!/usr/bin/env python3
"""Generates game/src/sim/trig_table.gd: a quarter-wave sine table in 16.16
fixed point, used by Fx.sin_a/cos_a/atan2_a.

The table is computed once, here, and committed as constants. Computing it at
runtime with floats could differ between CPUs and break determinism.

Angles use 4096 units per full turn (ANGLE_QUARTER = 1024), so the table has
1025 entries: sin(0) .. sin(90 degrees). Run: python3 tools/gen_trig_table.py
"""

import math
import os

ONE = 1 << 16
QUARTER = 1024
OUT = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                   "game", "src", "sim", "trig_table.gd")


def main():
    values = [int(math.floor(math.sin(i * math.pi / 2 / QUARTER) * ONE + 0.5)) for i in range(QUARTER + 1)]
    lines = []
    for i in range(0, len(values), 16):
        lines.append("\t" + ", ".join(str(v) for v in values[i:i + 16]) + ",")
    text = (
        "class_name TrigTable\n"
        "extends RefCounted\n"
        "## GENERATED by tools/gen_trig_table.py. Do not edit by hand.\n"
        "## sin(i * 90 degrees / 1024) in 16.16 fixed point, for i = 0..1024.\n\n"
        "const SINE_QUARTER: Array[int] = [\n" + "\n".join(lines) + "\n]\n"
    )
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("wrote %s (%d entries)" % (OUT, len(values)))


if __name__ == "__main__":
    main()
